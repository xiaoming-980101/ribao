export function isOpenRouterApiUrl(aiApiUrl: string = DEFAULT_AI_API_URL): boolean {
  return (aiApiUrl || '').toLowerCase().includes('openrouter.ai');
}

/**
 * 获取当前用户名：优先从 JWT token 中解码（避免信赖 localStorage 明文），
 * 降级从 localStorage 读取（兼容旧版本）。
 */
export function getCurrentUser(): string {
  const token = getAuthToken();
  if (token) {
    const parts = token.split('.');
    if (parts.length === 2) {
      try {
        const raw = atob(parts[0]);
        const payload = JSON.parse(raw);
        if (payload && payload.u) return payload.u;
      } catch (e) { /* 忽略解析失败 */ }
    }
  }
  return (localStorage.getItem('winner_daily_user') || '').trim().toLowerCase() || 'admin';
}

export function notifySettingsChanged() {
  window.dispatchEvent(new CustomEvent('winner-daily-settings-updated'));
}

function safeParseJSON<T>(raw: string | null): T | null {
  if (!raw) return null;
  try {
    return JSON.parse(raw) as T;
  } catch (e) {
    return null;
  }
}

export function getUserAISettings(user: string = getCurrentUser()): Partial<LocalAISettings> {
  const scoped = safeParseJSON<Partial<LocalAISettings>>(localStorage.getItem(`winner_daily_ai_settings_${user}`));
  if (scoped) return scoped;
  return safeParseJSON<Partial<LocalAISettings>>(localStorage.getItem('winner_daily_ai_settings')) || {};
}

export function saveUserAISettings(settings: Partial<LocalAISettings>, user: string = getCurrentUser()) {
  const nextSettings = {
    ...getUserAISettings(user),
    ...settings
  };
  localStorage.setItem(`winner_daily_ai_settings_${user}`, JSON.stringify(nextSettings));
  localStorage.setItem('winner_daily_ai_settings', JSON.stringify(nextSettings));
  notifySettingsChanged();
}

function getModelCacheKey(aiApiUrl: string = DEFAULT_AI_API_URL, user: string = getCurrentUser()) {
  return `winner_daily_cached_models_${user}_${encodeURIComponent(aiApiUrl || DEFAULT_AI_API_URL)}`;
}

export function loadCachedModels(aiApiUrl: string = DEFAULT_AI_API_URL, user: string = getCurrentUser()): ModelOption[] | null {
  const scoped = safeParseJSON<ModelOption[]>(localStorage.getItem(getModelCacheKey(aiApiUrl, user)));
  if (Array.isArray(scoped)) return scoped;

  if (!isOpenRouterApiUrl(aiApiUrl)) return null;

  const legacy = safeParseJSON<ModelOption[]>(localStorage.getItem('winner_daily_cached_models'));
  return Array.isArray(legacy) ? legacy : null;
}

export function saveCachedModels(models: ModelOption[], aiApiUrl: string = DEFAULT_AI_API_URL, user: string = getCurrentUser()) {
  localStorage.setItem(getModelCacheKey(aiApiUrl, user), JSON.stringify(models));
  notifySettingsChanged();
}

// 内存中的临时数据缓存，降级时使用
let memoryData: AppData = {
  logs: {},
  trash: {},
  reports: {},
  settings: DEFAULT_SETTINGS
};

// 从 LocalStorage 中读取
function getLocalStorageData(): AppData {
  try {
    const raw = localStorage.getItem('winner_daily_data');
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (e) {
    console.error('读取 LocalStorage 失败:', e);
  }
  return { logs: {}, trash: {}, reports: {}, settings: DEFAULT_SETTINGS };
}

// 写入 LocalStorage
function setLocalStorageData(data: AppData) {
  try {
    localStorage.setItem('winner_daily_data', JSON.stringify(data));
  } catch (e) {
    console.error('写入 LocalStorage 失败:', e);
  }
}

/**
 * 获取全部数据（日志+配置）
 */
export async function fetchAllData(): Promise<{ data: AppData; isOffline: boolean }> {
  try {
    const res = await fetch(`${BACKEND_URL}/api/data`, { 
      headers: getAuthHeaders(),
      signal: AbortSignal.timeout(2000) 
    });
    if (res.ok) {
      const data = await res.json();
      memoryData = data;
      // 同步写入本地 LocalStorage 备份
      setLocalStorageData(data);
      return { data, isOffline: false };
    }
  } catch (e) {
    console.warn('后端服务未启动或连接超时，正在降级为 LocalStorage 离线模式');
  }

  // 降级模式：读取 LocalStorage
  const localData = getLocalStorageData();
  memoryData = localData;
  return { data: localData, isOffline: true };
}

/**
 * 保存日志
 */
export async function saveLog(
  date: string,
  logData: Omit<LogEntry, 'updatedAt'>
): Promise<{ success: boolean; isOffline: boolean }> {
  const payload = { date, ...logData };

  try {
    const res = await fetch(`${BACKEND_URL}/api/logs`, {
      method: 'POST',
      headers: getAuthHeaders({ 'Content-Type': 'application/json' }),
      body: JSON.stringify(payload),
      signal: AbortSignal.timeout(2000)
    });
    if (res.ok) {
      // 同步更新 LocalStorage
      memoryData.logs[date] = {
        ...logData,
        updatedAt: new Date().toISOString()
      };
      setLocalStorageData(memoryData);
      return { success: true, isOffline: false };
    }
  } catch (e) {
    console.warn('保存日志至后端失败，正在写入本地 LocalStorage 离线存储');
  }

  // 降级模式：写入 LocalStorage 并入队待同步
  memoryData.logs[date] = {
    ...logData,
    updatedAt: new Date().toISOString()
  };
  setLocalStorageData(memoryData);
  enqueue({ kind: 'save_log', date, payload: { date, ...logData } });
  return { success: true, isOffline: true };
}

/**
 * 删除日志（软删除：移入回收站 trash，可在设置/回收站恢复）
 */
export async function deleteLog(date: string): Promise<{ success: boolean; isOffline: boolean }> {
  // 本地同步先将旧日志快照移入回收站
  const moveToLocalTrash = () => {
    if (memoryData.logs[date]) {
      memoryData.trash = memoryData.trash || {};
      memoryData.trash[date] = {
        ...memoryData.logs[date],
        deletedAt: new Date().toISOString()
      };
      delete memoryData.logs[date];
      setLocalStorageData(memoryData);
      return true;
    }
    return false;
  };

  try {
    const res = await fetch(`${BACKEND_URL}/api/logs/${date}`, {
      method: 'DELETE',
      headers: getAuthHeaders(),
      signal: AbortSignal.timeout(2000)
    });
    if (res.ok) {
      moveToLocalTrash();
      return { success: true, isOffline: false };
    }
  } catch (e) {
    console.warn('从后端删除日志失败，正在本地 LocalStorage 离线删除');
  }

  moveToLocalTrash();
  enqueue({ kind: 'delete_log', date });
  return { success: true, isOffline: true };
}

/**
 * 从回收站恢复指定日期的日志
 */
export async function restoreLog(date: string): Promise<{ success: boolean; isOffline: boolean }> {
  const restoreLocally = (): boolean => {
    if (memoryData.trash && memoryData.trash[date]) {
      const { deletedAt: _d, ...cleanLog } = memoryData.trash[date];
      memoryData.logs[date] = cleanLog;
      delete memoryData.trash[date];
      setLocalStorageData(memoryData);
      return true;
    }
    return false;
  };

  try {
    const res = await fetch(`${BACKEND_URL}/api/logs/${date}/restore`, {
      method: 'POST',
      headers: getAuthHeaders(),
      signal: AbortSignal.timeout(2000)
    });
    if (res.ok) {
      restoreLocally();
      return { success: true, isOffline: false };
    }
  } catch (e) {
    console.warn('在线恢复日志失败，降级本地恢复');
  }

  const ok = restoreLocally();
  if (ok) enqueue({ kind: 'restore_log', date });
  return { success: ok, isOffline: true };
}

