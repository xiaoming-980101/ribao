/**
 * 同步当前用户年挂的离线操作队列（网络恢复自动回放）。
 * 逐条执行真实服务器请求，成功后移除队列条目。
 * 供 App 挂载时 / 网络恢复时调用。
 */
export async function syncOfflineOperations(): Promise<{ successCount: number; failCount: number; done: boolean }> {
  return flushOfflineQueue(async (op) => {
    try {
      if (op.kind === 'reset') {
        const res = await fetch(`${BACKEND_URL}/api/reset`, {
          method: 'POST',
          headers: getAuthHeaders(),
          signal: AbortSignal.timeout(15000)
        });
        return res.ok;
      }
      if (op.kind === 'delete_log' && op.date) {
        const res = await fetch(`${BACKEND_URL}/api/logs/${op.date}`, {
          method: 'DELETE',
          headers: getAuthHeaders(),
          signal: AbortSignal.timeout(15000)
        });
        return res.ok;
      }
      if (op.kind === 'restore_log' && op.date) {
        const res = await fetch(`${BACKEND_URL}/api/logs/${op.date}/restore`, {
          method: 'POST',
          headers: getAuthHeaders(),
          signal: AbortSignal.timeout(15000)
        });
        return res.ok;
      }
      if (op.kind === 'clear_trash') {
        const res = await fetch(`${BACKEND_URL}/api/trash/clear`, {
          method: 'POST',
          headers: getAuthHeaders(),
          signal: AbortSignal.timeout(15000)
        });
        return res.ok;
      }
      if (op.kind === 'save_log' && op.date && op.payload) {
        const payload = op.payload;
        const res = await fetch(`${BACKEND_URL}/api/logs`, {
          method: 'POST',
          headers: getAuthHeaders({ 'Content-Type': 'application/json' }),
          body: JSON.stringify(payload),
          signal: AbortSignal.timeout(15000)
        });
        return res.ok;
      }
      if (op.kind === 'save_settings' && op.payload) {
        const res = await fetch(`${BACKEND_URL}/api/settings`, {
          method: 'POST',
          headers: getAuthHeaders({ 'Content-Type': 'application/json' }),
          body: JSON.stringify(op.payload),
          signal: AbortSignal.timeout(15000)
        });
        return res.ok;
      }
      if (op.kind === 'save_report' && op.payload && op.payload.weekKey) {
        const res = await fetch(`${BACKEND_URL}/api/reports/${op.payload.weekKey}`, {
          method: 'POST',
          headers: getAuthHeaders({ 'Content-Type': 'application/json' }),
          body: JSON.stringify({ content: op.payload.content }),
          signal: AbortSignal.timeout(15000)
        });
        return res.ok;
      }
      return true;
    } catch (e) {
      console.warn('[offlineQueue] 同步操作失败（下一轮重试）:', op.kind, op.date, e);
      return false;
    }
  });
}

import { DirectionOption } from '../types/ai';
import { generateLocalDirectionSuggestions } from './generator';

/**
 * 获取 AI 启发式工作方向推荐 (5 个切入点卡片)
 */
export async function fetchAIDirections(params: {
  job: string;
  customJobName?: string;
  mode: string;
  recentLogs?: any[];
  aiApiKey?: string;
  aiApiUrl?: string;
  aiModel?: string;
}): Promise<{ success: boolean; directions: DirectionOption[]; isOffline: boolean }> {
  try {
    const res = await fetch(`${BACKEND_URL}/api/ai/directions`, {
      method: 'POST',
      headers: getAuthHeaders({ 'Content-Type': 'application/json' }),
      body: JSON.stringify(params),
      signal: AbortSignal.timeout(180000)
    });

    if (res.ok) {
      const data = await res.json();
      if (data && data.directions && Array.isArray(data.directions) && data.directions.length > 0) {
        return { success: true, directions: data.directions, isOffline: !!data.isOffline };
      }
    }
  } catch (e) {
    console.warn('在线拉取方向建议失败，自动无缝降级为本地场景库:', e);
  }

  // 离线/兜底生成
  const localDirs = generateLocalDirectionSuggestions(params.job, params.mode, params.customJobName, params.recentLogs);
  return { success: true, directions: localDirs, isOffline: true };
}

